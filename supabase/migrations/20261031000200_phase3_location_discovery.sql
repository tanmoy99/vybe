create function public.import_suburbs(features jsonb, p_state text)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  n integer;
begin
  insert into public.suburbs (sal_code, name, state, centroid, boundary)
  select f -> 'properties' ->> 'sal_code_2021',
         regexp_replace(f -> 'properties' ->> 'sal_name_2021', '\s*\([^)]*\)$', ''),
         p_state,
         extensions.st_pointonsurface(g)::extensions.geography,
         g::extensions.geography
    from jsonb_array_elements(features) f,
         lateral (select extensions.st_multi(extensions.st_makevalid(
                    extensions.st_setsrid(extensions.st_geomfromgeojson(f ->> 'geometry'), 4326))) as g) geom
   where f -> 'geometry' is not null and f -> 'geometry' <> 'null'::jsonb
  on conflict (sal_code) do update
    set name = excluded.name, state = excluded.state, centroid = excluded.centroid, boundary = excluded.boundary;
  get diagnostics n = row_count;
  return n;
end;
$$;

create function public.import_region(p_code text, p_name text, geometry jsonb)
returns void
language sql
security definer
set search_path = ''
as $$
  insert into public.regions (code, name, boundary, source)
  values (p_code, p_name,
          extensions.st_multi(extensions.st_makevalid(extensions.st_setsrid(extensions.st_geomfromgeojson(geometry::text), 4326)))::extensions.geography,
          'ABS ASGS Edition 3 (2021) Greater Capital City Statistical Areas, CC BY 4.0')
  on conflict (code) do update set name = excluded.name, boundary = excluded.boundary;
  update public.suburbs s
     set region_code = case when extensions.st_intersects(r.boundary::extensions.geometry, s.centroid::extensions.geometry) then r.code
                            when s.region_code = r.code then null else s.region_code end
    from public.regions r
   where r.code = p_code;
$$;

revoke execute on function public.import_suburbs(jsonb, text) from public, anon, authenticated;
