-- At most 3 home-suburb changes per 30 days (anti-triangulation), audit-logged.
create function public.enforce_suburb_change_limit()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'UPDATE' and new.suburb_id = old.suburb_id then
    return new;
  end if;
  -- An upsert fires the INSERT trigger before resolving to an UPDATE; count it once, on the UPDATE.
  if tg_op = 'INSERT' and exists (select 1 from public.user_location_preferences where user_id = new.user_id) then
    return new;
  end if;
  if (select count(*) from public.suburb_change_log
       where user_id = new.user_id and changed_at > now() - interval '30 days') >= 3 then
    raise exception 'VYBE_SUBURB_CHANGE_LIMIT' using errcode = 'check_violation';
  end if;
  insert into public.suburb_change_log (user_id) values (new.user_id);
  insert into public.audit_logs (actor_id, action, target_type, target_id)
  values (new.user_id, 'location.suburb_changed', 'profile', new.user_id::text);
  return new;
end;
$$;

create trigger user_location_change_limit
  before insert or update on public.user_location_preferences
  for each row execute function public.enforce_suburb_change_limit();

