-- VYBE Phase 3: suburb reference data (PostGIS), home area, privacy-tiered discovery.
-- See docs/05-location-privacy.md and docs/04-matching-and-taxonomy.md.

create extension if not exists postgis with schema extensions;

create type public.location_source as enum ('manual', 'browser_suggested');

-- ---------------------------------------------------------------------------
-- Reference geography. Loaded by scripts/import-suburbs.mjs from the ABS
-- ASGS Edition 3 (2021) boundaries, © Australian Bureau of Statistics, CC BY 4.0.
-- ---------------------------------------------------------------------------
create table public.regions (
  code text primary key,
  name text not null,
  boundary extensions.geography(MultiPolygon, 4326) not null,
  source text not null
);

create table public.suburbs (
  id integer generated by default as identity primary key,
  sal_code text not null unique,
  name text not null,
  state text not null,
  postcode text,
  centroid extensions.geography(Point, 4326) not null,
  boundary extensions.geography(MultiPolygon, 4326),
  region_code text references public.regions (code),
  source text not null default 'ABS ASGS Edition 3 (2021) Suburbs and Localities, CC BY 4.0'
);
create index suburbs_centroid_gix on public.suburbs using gist (centroid);
create index suburbs_boundary_gix on public.suburbs using gist (boundary);
create index suburbs_name_idx on public.suburbs (lower(name) text_pattern_ops);

-- ---------------------------------------------------------------------------
-- Per-user location and discovery preferences
-- ---------------------------------------------------------------------------
create table public.user_location_preferences (
  user_id uuid primary key references public.profiles (id) on delete cascade,
  suburb_id integer not null references public.suburbs (id),
  source public.location_source not null default 'manual',
  updated_at timestamptz not null default now()
);
create index user_location_suburb_idx on public.user_location_preferences (suburb_id);

create table public.suburb_change_log (
  id bigint generated always as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  changed_at timestamptz not null default now()
);
create index suburb_change_log_user_idx on public.suburb_change_log (user_id, changed_at desc);

create table public.discovery_preferences (
  user_id uuid primary key references public.profiles (id) on delete cascade,
  -- Widest tier I discover and am discovered in: 2 local, 3 nearby, 4 Greater Sydney, 5 extended.
  max_tier smallint not null default 4 check (max_tier between 2 and 5),
  updated_at timestamptz not null default now()
);

create table public.blocks (
  blocker_id uuid not null references public.profiles (id) on delete cascade,
  blocked_id uuid not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker_id, blocked_id),
  check (blocker_id <> blocked_id)
);
create index blocks_blocked_idx on public.blocks (blocked_id);

create table public.discovery_requests (
  id bigint generated always as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  mode text not null,
  created_at timestamptz not null default now()
);
create index discovery_requests_user_idx on public.discovery_requests (user_id, created_at desc);

create trigger user_location_preferences_set_updated_at
