-- Eligible to appear in (and browse) discovery.
create function public.is_discoverable(uid uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
      from public.profiles p
      join public.profile_preferences pp on pp.user_id = p.id
      join public.user_privacy_settings ps on ps.user_id = p.id
      join public.user_location_preferences l on l.user_id = p.id
     where p.id = uid
       and p.account_status = 'active'
       and p.onboarding_completed_at is not null
       and ps.discoverable and not ps.discovery_paused
       and pp.intent is distinct from 'communities'
       and (select count(*) from public.user_interests ui where ui.user_id = uid and ui.visibility <> 'private') >= 5
  );
$$;

-- What the caller still needs before Radar opens.
create function public.my_discovery_readiness()
returns table (has_location boolean, interest_count integer, intent public.connection_intent, discoverable boolean, paused boolean)
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.user_location_preferences where user_id = (select auth.uid())),
         (select count(*)::int from public.user_interests where user_id = (select auth.uid()) and visibility <> 'private'),
         (select pp.intent from public.profile_preferences pp where pp.user_id = (select auth.uid())),
         (select ps.discoverable from public.user_privacy_settings ps where ps.user_id = (select auth.uid())),
         (select ps.discovery_paused from public.user_privacy_settings ps where ps.user_id = (select auth.uid()));
$$;

-- Suggest the suburb containing a point. Nothing is stored or logged.
create function public.suggest_suburb(lat double precision, lon double precision)
returns table (id integer, name text, state text)
language sql
stable
security definer
set search_path = ''
as $$
  select s.id, s.name, s.state
    from public.suburbs s
   where lat between -44 and -9 and lon between 112 and 154
     and s.boundary is not null
     and extensions.st_intersects(s.boundary, extensions.st_setsrid(extensions.st_point(lon, lat), 4326)::extensions.geography)
   limit 1;
$$;

-- ---------------------------------------------------------------------------
-- _discovery_pool(viewer): every candidate the viewer may see, with features and
-- score. Internal (no grants). Hard filters come first and can't be outweighed:
-- active+onboarded+discoverable, blocks (both ways), intentions, mutual dating
-- gender preferences, mutual age ranges, mutual tier limits.
-- ---------------------------------------------------------------------------
create function public._discovery_pool(v uuid)
returns table (
  candidate_id uuid,
  nickname text,
  age integer,
  intent public.connection_intent,
  connection_kind text,
  proximity_tier smallint,
  area_label text,
  score numeric,
  interest_score numeric,
  comm_score numeric,
  lang_score numeric,
  shared_count integer,
  shared jsonb,
  shared_hidden_count integer,
  shared_languages text[],
  highlights jsonb,
  social_energy public.social_energy,
  conversation_depth public.conversation_depth,
  chronotype public.chronotype,
  planning_style public.planning_style
)
language sql
stable
security definer
set search_path = ''
as $$
with me as (
  select p.id, p.gender, public.age_in_years(p.date_of_birth) as age, pp.intent, pp.dating_genders, pp.age_min, pp.age_max,
         pp.social_energy, pp.conversation_depth, pp.chronotype, pp.planning_style, pp.message_frequency, pp.group_size,
         l.suburb_id, s.centroid, s.region_code, coalesce(dp.max_tier, 4) as max_tier
    from public.profiles p
    join public.profile_preferences pp on pp.user_id = p.id
    join public.user_location_preferences l on l.user_id = p.id
    join public.suburbs s on s.id = l.suburb_id
    left join public.discovery_preferences dp on dp.user_id = p.id
   where p.id = v and public.is_discoverable(v)
),
suburb_pop as (
  select l.suburb_id, count(*) as n
    from public.user_location_preferences l
   where public.is_discoverable(l.user_id)
   group by l.suburb_id
),
pool as (
  select p.id, p.nickname::text as nickname, p.gender, public.age_in_years(p.date_of_birth) as age,
         pp.intent, pp.dating_genders, pp.age_min, pp.age_max, pp.social_energy, pp.conversation_depth, pp.chronotype,
         pp.planning_style, pp.message_frequency, pp.group_size,
         l.suburb_id, s.name as suburb_name, s.centroid, s.region_code, ps.hide_from_local, ps.show_area_label,
         coalesce(dp.max_tier, 4) as max_tier
    from public.profiles p
    join public.profile_preferences pp on pp.user_id = p.id
    join public.user_privacy_settings ps on ps.user_id = p.id
    join public.user_location_preferences l on l.user_id = p.id
    join public.suburbs s on s.id = l.suburb_id
    left join public.discovery_preferences dp on dp.user_id = p.id
   where p.id <> v
     and public.is_discoverable(p.id)
     and not exists (
       select 1 from public.blocks b
        where (b.blocker_id = v and b.blocked_id = p.id) or (b.blocker_id = p.id and b.blocked_id = v)
     )
),
eligible as (
  select c.*,
         (me.intent in ('dating', 'both') and c.intent in ('dating', 'both')
           and me.gender = any (c.dating_genders) and c.gender = any (me.dating_genders)) as dating_ok,
         (me.intent in ('friendship', 'both') and c.intent in ('friendship', 'both')) as friend_ok,
         case
           when c.suburb_id = me.suburb_id then 1
           when extensions.st_dwithin(c.centroid, me.centroid, 5000) then 2
           when extensions.st_dwithin(c.centroid, me.centroid, 15000) then 3
           when c.region_code is not null and c.region_code = me.region_code then 4
           else 5
         end as raw_tier
    from pool c, me
   where c.age between me.age_min and me.age_max
     and me.age between c.age_min and c.age_max
),
tiered as (
  select e.*,
         case
           when e.hide_from_local then greatest(e.raw_tier, 4)
           -- k-anonymity floor: small suburbs are never revealed as "local".
           when e.raw_tier <= 2 and coalesce((select sp.n from suburb_pop sp where sp.suburb_id = e.suburb_id), 0) < 10 then 3
           else e.raw_tier
         end::smallint as eff_tier
    from eligible e
   where e.dating_ok or e.friend_ok
),
cands as (
  select t.* from tiered t, me where t.eff_tier <= me.max_tier and t.eff_tier <= t.max_tier
),
-- Interest overlap: intensity-weighted cosine with rarity (IDF) weighting.
idf as (
  select ui.option_id, ln(1 + (select count(distinct user_id) from public.user_interests)::numeric / (1 + count(*))) as w
    from public.user_interests ui where ui.visibility <> 'private' group by ui.option_id
),
vi as (
  select ui.option_id, ui.intensity, ui.visibility from public.user_interests ui
   where ui.user_id = v and ui.visibility <> 'private'
),
ci as (
  select ui.user_id, ui.option_id, ui.intensity, ui.visibility from public.user_interests ui
   where ui.user_id in (select id from cands) and ui.visibility <> 'private'
),
vnorm as (select coalesce(sum(vi.intensity * idf.w), 0) as n from vi join idf using (option_id)),
cnorm as (select ci.user_id, sum(ci.intensity * idf.w) as n from ci join idf using (option_id) group by ci.user_id),
shared as (
  select ci.user_id, ci.option_id, least(ci.intensity, vi.intensity) * idf.w as sw,
         (ci.visibility = 'public' and vi.visibility = 'public') as both_public,
         (ci.intensity = 3 and vi.intensity = 3) as love_both,
         o.name, c.slug as category, c.world_name, s.category_id
    from ci
    join vi using (option_id)
    join idf using (option_id)
    join public.interest_options o on o.id = ci.option_id
    join public.interest_subcategories s on s.id = o.subcategory_id
    join public.interest_categories c on c.id = s.category_id
),
interest as (
  select cn.user_id,
         least(1, coalesce((select sum(sh.sw) from shared sh where sh.user_id = cn.user_id), 0)
                  / nullif(sqrt((select n from vnorm) * cn.n), 0)) as score,
         (select count(*)::int from shared sh where sh.user_id = cn.user_id) as shared_count,
         (select count(*)::int from shared sh where sh.user_id = cn.user_id and not sh.both_public) as hidden_count,
         coalesce((select jsonb_agg(jsonb_build_object('name', x.name, 'category', x.category, 'world', x.world_name, 'love', x.love_both)
                                    order by x.love_both desc, x.sw desc)
                     from (select * from shared sh where sh.user_id = cn.user_id and sh.both_public
                            order by sh.love_both desc, sh.sw desc limit 12) x), '[]'::jsonb) as shared
    from cnorm cn
),
activity as (
  select c.id as user_id,
         coalesce(
           (select count(*) from ci join vi using (option_id)
              join public.interest_options o on o.id = ci.option_id
              join public.interest_subcategories s on s.id = o.subcategory_id
              join public.interest_categories cat on cat.id = s.category_id
             where ci.user_id = c.id and cat.slug in ('road-trips', 'active', 'sports', 'gaming'))::numeric
           / nullif((select count(distinct x.option_id) from (
                select ci.option_id from ci where ci.user_id = c.id
                union select vi.option_id from vi) x
              join public.interest_options o on o.id = x.option_id
              join public.interest_subcategories s on s.id = o.subcategory_id
              join public.interest_categories cat on cat.id = s.category_id
             where cat.slug in ('road-trips', 'active', 'sports', 'gaming')), 0), 0) as score
    from cands c
),
lang as (
  select c.id as user_id,
         coalesce(max(case
           when vl.prefers_chatting and cl.prefers_chatting then 1.0
           when vl.proficiency <> 'learning' and cl.proficiency <> 'learning' then 0.6
           when (vl.proficiency = 'learning') <> (cl.proficiency = 'learning') then 0.3
           else 0.1 end), 0) as score,
         coalesce(array_agg(lg.name order by lg.sort_order)
                    filter (where vl.proficiency <> 'learning' and cl.proficiency <> 'learning'), '{}') as shared_names
    from cands c
    left join public.user_languages cl on cl.user_id = c.id
    left join public.user_languages vl on vl.user_id = v and vl.language_code = cl.language_code
    left join public.languages lg on lg.code = vl.language_code
   group by c.id
),
scored as (
  select c.*,
         coalesce(i.score, 0) as i_score,
         coalesce(i.shared_count, 0) as i_count,
         coalesce(i.hidden_count, 0) as i_hidden,
         coalesce(i.shared, '[]'::jsonb) as i_shared,
         a.score as a_score,
         lg.score as l_score,
         lg.shared_names,
         (
           (case when c.social_energy = me.social_energy then 1 when 'ambivert' in (c.social_energy, me.social_energy) then 0.6 else 0.3 end)
         + (case when c.conversation_depth = me.conversation_depth then 1 when 'both' in (c.conversation_depth, me.conversation_depth) then 0.75 else 0.25 end)
         + (case when c.chronotype = me.chronotype or 'flexible' in (c.chronotype, me.chronotype) then 1 else 0.3 end)
         + (case when c.planning_style = me.planning_style or 'mix' in (c.planning_style, me.planning_style) then 1 else 0.3 end)
         + (case when c.message_frequency = me.message_frequency then 1 when 'daily' in (c.message_frequency, me.message_frequency) then 0.6 else 0.3 end)
         + (case when c.group_size = me.group_size or 'any' in (c.group_size, me.group_size) then 1 else 0.4 end)
         ) / 6.0 as c_score,
         (case when c.intent = me.intent then 1.0 else 0.7 end) as t_score
    from cands c
    cross join me
    left join interest i on i.user_id = c.id
    join activity a on a.user_id = c.id
    join lang lg on lg.user_id = c.id
)
select s.id,
       s.nickname,
       s.age,
       s.intent,
       case when s.dating_ok and s.friend_ok then 'dating_or_friendship' when s.dating_ok then 'dating' else 'friendship' end,
       -- Tiers 1 and 2 share one label so "same suburb" is never distinguishable.
       greatest(s.eff_tier, 2)::smallint,
       case when s.show_area_label then regexp_replace(s.suburb_name, '\s*\([^)]*\)$', '') end,
       round(0.30 * s.i_score
             + 0.20 * (case s.eff_tier when 1 then 1.0 when 2 then 0.8 when 3 then 0.55 when 4 then 0.3 else 0.1 end)
             + 0.20 * s.t_score + 0.10 * s.l_score + 0.10 * s.a_score + 0.10 * s.c_score, 4),
       round(s.i_score, 4),
       round(s.c_score, 4),
       round(s.l_score, 4),
       s.i_count,
       s.i_shared,
       s.i_hidden,
       s.shared_names,
       coalesce((select jsonb_agg(jsonb_build_object('name', h.name, 'world', h.world_name) order by h.intensity desc, h.name)
                   from (select o.name, cat.world_name, ui.intensity
                           from public.user_interests ui
                           join public.interest_options o on o.id = ui.option_id
                           join public.interest_subcategories sc on sc.id = o.subcategory_id
                           join public.interest_categories cat on cat.id = sc.category_id
                          where ui.user_id = s.id and ui.visibility = 'public'
                          order by ui.intensity desc, o.name limit 8) h), '[]'::jsonb),
       s.social_energy,
       s.conversation_depth,
       s.chronotype,
       s.planning_style
  from scored s;
$$;

revoke execute on function public._discovery_pool(uuid) from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- discover_candidates(): the public discovery API. Rate-limited, paginated,
-- returns only public-safe fields (no coordinates, distances, raw scores or
-- private/matching-only interest names).
--   p_mode: 'all' | 'taste_twin' | 'opposite'; p_category: world slug filter.
-- ---------------------------------------------------------------------------
create function public.discover_candidates(
  p_mode text default 'all',
  p_category text default null,
  p_limit integer default 24,
  p_offset integer default 0
)
returns table (
  candidate_id uuid,
  nickname text,
  age integer,
  intent public.connection_intent,
  connection_kind text,
  proximity_tier smallint,
  area_label text,
  wavelength smallint,
  shared_count integer,
  shared jsonb,
  shared_hidden_count integer,
  shared_languages text[],
  highlights jsonb,
  social_energy public.social_energy,
  conversation_depth public.conversation_depth,
  chronotype public.chronotype,
  planning_style public.planning_style
)
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v uuid := (select auth.uid());
begin
  if v is null then
    raise exception 'Not authenticated' using errcode = 'insufficient_privilege';
  end if;
  if p_mode not in ('all', 'taste_twin', 'opposite') then
    raise exception 'Unknown discovery mode' using errcode = 'invalid_parameter_value';
  end if;
  if (select count(*) from public.discovery_requests
       where user_id = v and created_at > now() - interval '1 hour') >= 120 then
    raise exception 'VYBE_RATE_LIMITED' using errcode = 'P0001';
  end if;
  insert into public.discovery_requests (user_id, mode) values (v, p_mode);

  p_limit := least(greatest(coalesce(p_limit, 24), 1), 30);
  p_offset := least(greatest(coalesce(p_offset, 0), 0), 300);

  return query
  select d.candidate_id, d.nickname, d.age, d.intent, d.connection_kind, d.proximity_tier, d.area_label,
         (case when d.score >= 0.6 then 3 when d.score >= 0.4 then 2 else 1 end)::smallint,
         d.shared_count, d.shared, d.shared_hidden_count, d.shared_languages, d.highlights,
         d.social_energy, d.conversation_depth, d.chronotype, d.planning_style
    from public._discovery_pool(v) d
   where (p_mode <> 'taste_twin' or d.shared_count >= 5)
     and (p_mode <> 'opposite' or (d.lang_score > 0 and d.shared_count between 1 and 4 and d.comm_score >= 0.7))
     and (p_category is null or exists (
           select 1 from jsonb_array_elements(d.shared) x where x ->> 'category' = p_category))
   order by
     case when p_mode = 'all' then d.proximity_tier end asc,
     case when p_mode = 'taste_twin' then d.interest_score when p_mode = 'opposite' then d.comm_score end desc nulls last,
     round(d.score, 1) desc,
     -- Stable per-viewer, per-day jitter so repeated queries don't leak exact rank.
     md5(v::text || d.candidate_id::text || current_date::text)
   limit p_limit offset p_offset;
end;
$$;

-- ---------------------------------------------------------------------------
-- Admin import helpers (service role only)
