-- VYBE Phase 2: hierarchical interest taxonomy (admin-editable) and user interests.

create type public.interest_visibility as enum ('public', 'matching_only', 'private');
create type public.subcategory_kind as enum ('multi', 'single', 'text');

create table public.interest_categories (
  id smallint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9-]{2,40}$'),
  name text not null check (char_length(name) between 2 and 40),
  world_name text not null check (char_length(world_name) between 2 and 40),
  description text check (char_length(description) <= 200),
  hue text not null default 'violet' check (hue in ('violet', 'indigo', 'blush')),
  sort_order smallint not null default 100,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.interest_subcategories (
  id integer generated by default as identity primary key,
  category_id smallint not null references public.interest_categories (id) on delete cascade,
  slug text not null check (slug ~ '^[a-z0-9-]{2,40}$'),
  name text not null check (char_length(name) between 2 and 60),
  prompt text check (char_length(prompt) <= 160),
  kind public.subcategory_kind not null default 'multi',
  default_visibility public.interest_visibility not null default 'public',
  sort_order smallint not null default 100,
  is_active boolean not null default true,
  unique (category_id, slug)
);

create table public.interest_options (
  id integer generated by default as identity primary key,
  subcategory_id integer not null references public.interest_subcategories (id) on delete cascade,
  slug text not null check (slug ~ '^[a-z0-9-]{1,60}$'),
  name text not null check (char_length(name) between 1 and 60),
  sort_order smallint not null default 100,
  is_active boolean not null default true,
  unique (subcategory_id, slug)
);

create table public.user_interests (
  user_id uuid not null references public.profiles (id) on delete cascade,
  option_id integer not null references public.interest_options (id) on delete cascade,
  intensity smallint not null default 2 check (intensity between 1 and 3),
  visibility public.interest_visibility not null default 'public',
  created_at timestamptz not null default now(),
  primary key (user_id, option_id)
);
create index user_interests_option_idx on public.user_interests (option_id);

create table public.user_interest_details (
  user_id uuid not null references public.profiles (id) on delete cascade,
  subcategory_id integer not null references public.interest_subcategories (id) on delete cascade,
  details text not null check (char_length(details) between 1 and 280),
  visibility public.interest_visibility not null default 'public',
  updated_at timestamptz not null default now(),
  primary key (user_id, subcategory_id)
);

create trigger user_interest_details_set_updated_at
  before update on public.user_interest_details
  for each row execute function public.set_updated_at();

create function public.enforce_user_interest_limit()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if (select count(*) from public.user_interests where user_id = new.user_id) >= 200 then
    raise exception 'You can add up to 200 interests.' using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

create trigger user_interests_limit
  before insert on public.user_interests
  for each row execute function public.enforce_user_interest_limit();

-- ---------------------------------------------------------------------------
-- set_my_category_interests(): atomically replace the caller's choices within
-- one category. SECURITY INVOKER so RLS applies.
--   choices: [{"option_id": 12, "intensity": 3}, ...]
--   visibility: {"<subcategory_id>": "public" | "matching_only" | "private", ...}
--   details: [{"subcategory_id": 7, "details": "Parasite, Memories of Murder"}, ...]
-- ---------------------------------------------------------------------------
create function public.set_my_category_interests(p_category_id smallint, choices jsonb, visibility jsonb, details jsonb)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  uid uuid := (select auth.uid());
begin
  if uid is null then
    raise exception 'Not authenticated' using errcode = 'insufficient_privilege';
  end if;
  if jsonb_typeof(choices) <> 'array' or jsonb_typeof(details) <> 'array' or jsonb_typeof(visibility) <> 'object' then
    raise exception 'Invalid payload' using errcode = 'invalid_parameter_value';
  end if;

  -- Every chosen option must be active and belong to this category.
  if exists (
    select 1
      from jsonb_array_elements(choices) c
      left join public.interest_options o on o.id = (c ->> 'option_id')::int and o.is_active
      left join public.interest_subcategories s on s.id = o.subcategory_id and s.is_active and s.kind <> 'text'
     where s.category_id is distinct from p_category_id
  ) then
    raise exception 'VYBE_OPTION_NOT_IN_CATEGORY' using errcode = 'invalid_parameter_value';
  end if;

  -- Single-choice subcategories accept at most one option.
  if exists (
    select 1
      from jsonb_array_elements(choices) c
      join public.interest_options o on o.id = (c ->> 'option_id')::int
      join public.interest_subcategories s on s.id = o.subcategory_id
     where s.kind = 'single'
     group by s.id
    having count(*) > 1
  ) then
    raise exception 'VYBE_SINGLE_CHOICE' using errcode = 'invalid_parameter_value';
  end if;

  delete from public.user_interests ui
   using public.interest_options o, public.interest_subcategories s
   where ui.user_id = uid and o.id = ui.option_id and s.id = o.subcategory_id and s.category_id = p_category_id;

  insert into public.user_interests (user_id, option_id, intensity, visibility)
  select uid,
         (c ->> 'option_id')::int,
         coalesce((c ->> 'intensity')::smallint, 2),
         coalesce((visibility ->> s.id::text)::public.interest_visibility, s.default_visibility)
    from jsonb_array_elements(choices) c
    join public.interest_options o on o.id = (c ->> 'option_id')::int
    join public.interest_subcategories s on s.id = o.subcategory_id;

  delete from public.user_interest_details d
   using public.interest_subcategories s
   where d.user_id = uid and s.id = d.subcategory_id and s.category_id = p_category_id;

  insert into public.user_interest_details (user_id, subcategory_id, details, visibility)
  select uid, s.id, trim(d ->> 'details'),
         coalesce((visibility ->> s.id::text)::public.interest_visibility, s.default_visibility)
    from jsonb_array_elements(details) d
    join public.interest_subcategories s
      on s.id = (d ->> 'subcategory_id')::int and s.category_id = p_category_id and s.kind = 'text' and s.is_active
   where char_length(trim(d ->> 'details')) > 0;
end;
$$;

