grant execute on function public.discover_candidates(text, text, integer, integer) to authenticated;

alter table public.regions enable row level security;
alter table public.suburbs enable row level security;
alter table public.user_location_preferences enable row level security;
alter table public.suburb_change_log enable row level security;
alter table public.discovery_preferences enable row level security;
alter table public.blocks enable row level security;
alter table public.discovery_requests enable row level security;

create policy "Suburbs: read" on public.suburbs for select to authenticated using (true);

create policy "Own location: read" on public.user_location_preferences for select to authenticated
  using (user_id = (select auth.uid()));
create policy "Own location: insert" on public.user_location_preferences for insert to authenticated
  with check (user_id = (select auth.uid()));
create policy "Own location: update" on public.user_location_preferences for update to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

create policy "Own discovery prefs: read" on public.discovery_preferences for select to authenticated
  using (user_id = (select auth.uid()));
create policy "Own discovery prefs: insert" on public.discovery_preferences for insert to authenticated
  with check (user_id = (select auth.uid()));
create policy "Own discovery prefs: update" on public.discovery_preferences for update to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

-- Blockers manage their own blocks; the blocked person is never told.
create policy "Own blocks: read" on public.blocks for select to authenticated using (blocker_id = (select auth.uid()));
create policy "Own blocks: insert" on public.blocks for insert to authenticated with check (blocker_id = (select auth.uid()));
create policy "Own blocks: delete" on public.blocks for delete to authenticated using (blocker_id = (select auth.uid()));
