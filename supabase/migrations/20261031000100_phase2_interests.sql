create function pg_temp.slugify(t text) returns text language sql immutable as $$
  select trim(both '-' from regexp_replace(lower(t), '[^a-z0-9]+', '-', 'g'))
$$;

create function pg_temp.seed_sub(cat text, sub_name text, sub_prompt text, sub_kind public.subcategory_kind,
                                 opts text[], vis public.interest_visibility default 'public', sort smallint default 100)
returns void language plpgsql as $$
declare
  sid int;
begin
  insert into public.interest_subcategories (category_id, slug, name, prompt, kind, default_visibility, sort_order)
  values ((select id from public.interest_categories where slug = cat), pg_temp.slugify(sub_name), sub_name,
          sub_prompt, sub_kind, vis, sort)
  returning id into sid;
  insert into public.interest_options (subcategory_id, slug, name, sort_order)
  select sid, pg_temp.slugify(o), o, (row_number() over ())::smallint from unnest(opts) as o;
end;
$$;

